#5.1. Suma (+)
producto1 = int(input("Ingresa el cantidad de  lapices: "))
producto2 = int(input("Ingresa tu cantidad de cuadernos: "))

print(producto1 + producto2)
#5.2. Resta (-)
presupuesto = int(input("Ingresa tu presupuesto: "))
compra = int(input("Ingresa tus compra : "))
print(presupuesto - compra)

#5.3. Multiplicación (*)

entrada_coste = int(input("Ingresa coste de entradas: "))
cantidad_entradas = int(input("Ingresa cuantas entradas compraste : "))
print(entrada_coste * cantidad_entradas)



#5.4. División (/)
donaciones = int(input("Ingresa cantidad de manzanas: "))
personas = int(input("Ingresa personas en las cuales se dividiran las manzanas: "))
print(donaciones / personas)


#5.5. División entera (//)
estudiantes = int(input("Ingresa cantidad de estudiantes: "))
equipo = int(input("Ingresa cantidad de equipos: "))
print(equipo // estudiantes)


#5.6. Módulo (%)
estudiantes_segundo = int(input("Ingresa cantidad de estudiantes: "))
equipo_dos = int(input("Ingresa cantidad de equipos: "))
print(estudiantes_segundo % equipo_dos)


#5.7. Potencia (**)
base = int(input("Ingresa numero base: "))
exponente = int(input("Ingresa numero exponente: "))
print(base ** exponente)

